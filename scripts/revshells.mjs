#!/usr/bin/env node
// Regenerate apps/web/lib/tools/revshells/payloads.generated.ts from the pinned
// upstream snapshot in vendor/revshells/data.js.
//
// The upstream data.js (revshells.com, MIT © 2022 Ryan Montgomery) is CommonJS
// that assigns `exports.rsgData`. We require it, then re-serialise the parts we
// use as JSON literals so every command string is preserved byte-for-byte. To
// refresh after bumping integration/revshells/upstream.json, replace
// vendor/revshells/data.js with the new snapshot and run:
//     node scripts/revshells.mjs
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = new URL("..", import.meta.url);

const dataPath = fileURLToPath(new URL("vendor/revshells/data.js", root));
const pinPath = fileURLToPath(new URL("integration/revshells/upstream.json", root));
const outPath = fileURLToPath(new URL("apps/web/lib/tools/revshells/payloads.generated.ts", root));

const { rsgData } = require(dataPath);
const pin = JSON.parse(readFileSync(pinPath, "utf8"));

if (!rsgData?.reverseShellCommands?.length) {
    throw new Error("vendor/revshells/data.js did not export the expected rsgData.reverseShellCommands");
}

// reverseShellCommands already folds in bind-shell, msfvenom, hoaxshell and
// assembled commands (each tagged with its CommandType in element.meta).
const commands = rsgData.reverseShellCommands.map(({ name, command, meta }) => ({ name, command, meta }));
const listeners = rsgData.listenerCommands.map(([name, command]) => ({ name, command }));
const shells = rsgData.shells;
const special = rsgData.specialCommands;

const json = (value) => JSON.stringify(value, null, 4);

const banner = `// AUTO-GENERATED — DO NOT EDIT BY HAND.
// Generated by scripts/revshells.mjs from vendor/revshells/data.js
// Upstream: ${pin.repository} @ ${pin.commit}
// Reverse Shell Generator (revshells.com), MIT © 2022 Ryan Montgomery.
// Regenerate with: node scripts/revshells.mjs
`;

const body = `${banner}
import type { Command, Listener, SpecialCommands } from "./types.ts";

/** Every reverse-shell, bind-shell, MSFVenom, HoaxShell and assembled command. */
export const commands: readonly Command[] = ${json(commands)};

/** Listener one-liners for catching an incoming shell. */
export const listeners: readonly Listener[] = ${json(listeners)};

/** Shells offered in the shell selector. */
export const shells: readonly string[] = ${json(shells)};

/** Commands whose encoding is special-cased (PowerShell base64 variants). */
export const specialCommands: SpecialCommands = ${json(special)};
`;

writeFileSync(outPath, body);
console.log(
    `revshells: wrote ${commands.length} commands, ${listeners.length} listeners, ${shells.length} shells -> ${outPath.replace(fileURLToPath(root), "")}`,
);
