#!/usr/bin/env node
// Regenerate apps/web/lib/tools/gtfobins/data.generated.ts from the pinned
// upstream snapshot in vendor/gtfobins/.
//
// Each upstream entry is a YAML document in _gtfobins/<executable> (no file
// extension), wrapped in `---` / `...`. The function and context definitions
// (labels, descriptions, helper snippets) live in _data/*.yml. YAML anchors are
// resolved by the parser, and everything is re-serialised as JSON so code and
// comment strings survive byte-for-byte. To refresh after bumping
// integration/gtfobins/upstream.json, replace vendor/gtfobins/ with the new
// snapshot and run:
//     node scripts/gtfobins.mjs
import yaml from "js-yaml";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const path = (relative) => fileURLToPath(new URL(relative, root));
const vendor = path("vendor/gtfobins/");
const outPath = path("apps/web/lib/tools/gtfobins/data.generated.ts");
const pin = JSON.parse(readFileSync(path("integration/gtfobins/upstream.json"), "utf8"));

const loadData = (name) => yaml.load(readFileSync(`${vendor}_data/${name}.yml`, "utf8"));
const functionDefs = loadData("functions");
const contextDefs = loadData("contexts");

const describe = (defs) =>
    Object.entries(defs).map(([id, { label, description, extra }]) => ({
        id,
        label,
        description,
        ...(extra ? { extra } : {}),
    }));
const functions = describe(functionDefs);
const contexts = describe(contextDefs);

const entries = readdirSync(`${vendor}_gtfobins`)
    .sort()
    .map((name) => {
        const text = readFileSync(`${vendor}_gtfobins/${name}`, "utf8");
        const document = text.split(/^---$/m)[1]?.replace(/^\.\.\.\s*$/m, "");
        const data = yaml.load(document ?? "") ?? {};
        const out = { name };
        if (data.alias) out.alias = data.alias;
        if (data.comment) out.comment = data.comment;
        out.functions = {};
        for (const [fn, examples] of Object.entries(data.functions ?? {})) {
            if (!functionDefs[fn]) throw new Error(`${name}: unknown function "${fn}"`);
            out.functions[fn] = examples.map((example) => {
                const contextsOut = {};
                for (const [ctx, detail] of Object.entries(example.contexts ?? {})) {
                    if (!contextDefs[ctx]) throw new Error(`${name}/${fn}: unknown context "${ctx}"`);
                    contextsOut[ctx] = detail ?? {};
                }
                return { ...example, contexts: contextsOut };
            });
        }
        return out;
    });

const names = new Set(entries.map((entry) => entry.name));
for (const entry of entries) {
    if (entry.alias && !names.has(entry.alias)) throw new Error(`${entry.name}: alias target "${entry.alias}" does not exist`);
    if (entry.alias && Object.keys(entry.functions).length) throw new Error(`${entry.name}: has both an alias and functions`);
}

const lines = (items) => items.map((item) => `    ${JSON.stringify(item)},`).join("\n");

const body = `// AUTO-GENERATED — DO NOT EDIT BY HAND.
// Generated by scripts/gtfobins.mjs from vendor/gtfobins/
// Upstream: ${pin.repository} @ ${pin.commit}
// GTFOBins (gtfobins.org), GPL-3.0. See integration/gtfobins/NOTICE.
// Regenerate with: node scripts/gtfobins.mjs

import type { ContextInfo, Entry, FunctionInfo } from "./types.ts";

/** What each kind of function means, plus the helper snippets for the attacker side. */
export const functionInfo: readonly FunctionInfo[] = [
${lines(functions)}
];

/** The privilege contexts an example can run in. */
export const contextInfo: readonly ContextInfo[] = [
${lines(contexts)}
];

/** Every executable, sorted by name. Aliases point at the entry that holds their functions. */
export const entries: readonly Entry[] = [
${lines(entries)}
];
`;

writeFileSync(outPath, body);
const examples = entries.reduce((sum, e) => sum + Object.values(e.functions).flat().length, 0);
console.log(`gtfobins: wrote ${entries.length} executables, ${examples} examples -> ${outPath.replace(fileURLToPath(root), "")}`);
